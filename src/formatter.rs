use crate::stats::{FileResult, RepoStats};

/// Format an integer with comma thousands separators (e.g. 10000 -> "10,000").
pub fn format_thousands(n: usize) -> String {
    let s = n.to_string();
    let mut result = String::new();
    let chars: Vec<char> = s.chars().collect();
    let len = chars.len();
    for (i, &c) in chars.iter().enumerate() {
        if i > 0 && (len - i).is_multiple_of(3) {
            result.push(',');
        }
        result.push(c);
    }
    result
}

fn format_code_span(text: &str) -> String {
    let longest_run = text.split(|c| c != '`').map(str::len).max().unwrap_or(0);
    let delimiter_len = if longest_run == 0 { 1 } else { longest_run + 1 };
    let delimiter = "`".repeat(delimiter_len);
    format!("{delimiter}{text}{delimiter}")
}

/// Format repository metadata and the file index for logging.
pub fn format_context_summary(results: &[FileResult], stats: &RepoStats) -> String {
    let mut lines = Vec::new();

    lines.push("# Codebase Context".to_string());
    lines.push(format!(
        "> Generated by `skel` (Tokens compressed from {} to {}, -{:.1}%)\n",
        format_thousands(stats.orig_tokens),
        format_thousands(stats.skel_tokens),
        stats.ratio
    ));
    lines.push("## Summary of Included Files".to_string());
    lines.push("| File | Mode | Language | Tokens |".to_string());
    lines.push("| :--- | :--- | :--- | :--- |".to_string());

    for r in results {
        let table_path = format_code_span(&r.path.replace('|', "\\|"));
        lines.push(format!(
            "| {table_path} | **{}** | {} | {} |",
            r.mode,
            r.lang,
            format_thousands(r.skel_tokens)
        ));
    }

    lines.push("\n---\n".to_string());

    lines.join("\n")
}

/// Format per-file source sections without repository metadata.
/// The statistics argument is retained for compatibility with library callers.
pub fn format_markdown(results: &[FileResult], _stats: &RepoStats) -> String {
    let mut lines = Vec::new();

    for r in results {
        let file_path = format_code_span(&r.path);
        lines.push(format!("### File: {file_path} ({})", r.mode));
        // Docstrings and comments can contain fenced examples themselves.
        let longest_run = r
            .content
            .split(|c| c != '`')
            .map(str::len)
            .max()
            .unwrap_or(0);
        let fence = "`".repeat(3.max(longest_run + 1));
        lines.push(format!("{fence}{}\n{}\n{fence}\n", r.lang, r.content));
    }

    lines.join("\n")
}

/// Format terminal summary report.
pub fn format_terminal_report(stats: &RepoStats, version: &str) -> String {
    format!(
        "\n{sep}\n [skel v{version}] Codebase Context Compression Report\n{divider}\n \
         Files processed:    {}\n \
         Original tokens:    {}\n \
         Skeleton tokens:    {}\n \
         Compression ratio:  {:.1}% reduction\n \
         Est. cost saved:    ${:.4} (Claude 3.5 Sonnet tier)\n{sep}\n",
        stats.file_count,
        format_thousands(stats.orig_tokens),
        format_thousands(stats.skel_tokens),
        stats.ratio,
        stats.savings_usd,
        sep = "=".repeat(60),
        divider = "-".repeat(60),
        version = version
    )
}
