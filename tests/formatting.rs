use skel::formatter::format_thousands;
use skel::{
    compute_stats, estimate_tokens, format_markdown, format_terminal_report, FileResult, RepoStats,
};

fn file(
    path: &str,
    language: &str,
    mode: &str,
    original: usize,
    pruned: usize,
    content: &str,
) -> FileResult {
    FileResult {
        path: path.into(),
        lang: language.into(),
        mode: mode.into(),
        orig_tokens: original,
        skel_tokens: pruned,
        content: content.into(),
    }
}

fn assert_near(actual: f64, expected: f64) {
    assert!(
        (actual - expected).abs() < 1e-10,
        "Expected {expected}, got {actual}"
    );
}

#[test]
fn token_estimates_cover_empty_minimum_rounding_and_multibyte_text() {
    for (text, expected) in [
        ("", 0),
        ("a", 1),
        ("ab", 1),
        ("abc", 1),
        ("abcd", 1),
        ("abcde", 1),
        ("abcdef", 2),
        ("abcdefg", 2),
        ("abcdefgh", 2),
        ("abcdefghi", 3),
        ("abcdefghij", 3),
        ("中文", 2),
        ("🐾", 1),
        ("🐾🐾", 2),
        ("a中🐾", 2),
        (" \t\r\n", 1),
    ] {
        assert_eq!(estimate_tokens(text), expected, "{text:?}");
    }
    assert_eq!(estimate_tokens(&"x".repeat(3_500)), 1_000);
}

#[test]
fn token_estimates_are_monotonic_across_rounding_boundaries() {
    let mut previous = 0;
    for length in 0..2_048 {
        let current = estimate_tokens(&"x".repeat(length));
        assert!(
            current >= previous && current <= previous + 1,
            "length {length}"
        );
        previous = current;
    }
}

#[test]
fn empty_statistics_are_finite_and_zero() {
    let stats = compute_stats(&[]);
    assert_eq!(stats.file_count, 0);
    assert_eq!(
        (stats.orig_tokens, stats.skel_tokens, stats.saved_tokens),
        (0, 0, 0)
    );
    assert_eq!(stats.ratio, 0.0);
    assert_eq!(stats.savings_usd, 0.0);
}

#[test]
fn statistics_aggregate_mixed_modes_and_illustrative_cost() {
    let results = [
        file("a.py", "python", "FULL", 1_000, 1_000, ""),
        file("b.ts", "typescript", "SKELETON", 3_000, 500, ""),
        file("c.rs", "rust", "UNCHANGED", 1_000, 1_000, ""),
    ];
    let stats = compute_stats(&results);
    assert_eq!(stats.file_count, 3);
    assert_eq!(
        (stats.orig_tokens, stats.skel_tokens, stats.saved_tokens),
        (5_000, 2_500, 2_500)
    );
    assert_near(stats.ratio, 50.0);
    assert_near(stats.savings_usd, 0.0075);
}

#[test]
fn larger_skeletons_do_not_underflow_or_report_negative_savings() {
    for (original, skeleton) in [(0, 10), (1, 10), (10, 10)] {
        let stats = compute_stats(&[file(
            "empty.ts",
            "typescript",
            "SKELETON",
            original,
            skeleton,
            "",
        )]);
        assert_eq!(stats.saved_tokens, 0);
        assert_eq!(stats.ratio, 0.0);
        assert_eq!(stats.savings_usd, 0.0);
    }
}

#[test]
fn savings_are_computed_after_aggregation_and_support_full_reduction() {
    let stats = compute_stats(&[
        file("a", "python", "SKELETON", 10, 20, ""),
        file("b", "python", "SKELETON", 90, 0, ""),
    ]);
    assert_eq!(stats.saved_tokens, 80);
    assert_near(stats.ratio, 80.0);
    let reduced = compute_stats(&[file("a", "python", "SKELETON", 100, 0, "")]);
    assert_eq!(reduced.saved_tokens, 100);
    assert_near(reduced.ratio, 100.0);
}

#[test]
fn thousands_separators_cover_every_group_boundary_and_usize_max() {
    for (number, expected) in [
        (0, "0"),
        (1, "1"),
        (12, "12"),
        (123, "123"),
        (999, "999"),
        (1_000, "1,000"),
        (9_999, "9,999"),
        (10_000, "10,000"),
        (999_999, "999,999"),
        (1_000_000, "1,000,000"),
        (1_234_567_890, "1,234,567,890"),
    ] {
        assert_eq!(format_thousands(number), expected);
    }
    let formatted = format_thousands(usize::MAX);
    assert_eq!(formatted.replace(',', ""), usize::MAX.to_string());
    assert!(formatted.split(',').skip(1).all(|group| group.len() == 3));
}

