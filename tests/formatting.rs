#[test]
fn markdown_golden_covers_header_table_order_modes_and_exact_source() {
    let results = [
        file("src/z.py", "python", "FULL", 1_000, 1_000, "value = 1\n"),
        file(
            "src/a.ts",
            "typescript",
            "SKELETON",
            3_000,
            500,
            "function f() { /* ... */ }",
        ),
    ];
    let original = results
        .iter()
        .map(|r| r.content.clone())
        .collect::<Vec<_>>();
    assert_eq!(
        format_markdown(&results, &compute_stats(&results)),
        concat!(
            "# Codebase Context\n",
            "> Generated by `skel` (Tokens compressed from 4,000 to 1,500, -62.5%)\n\n",
            "## Summary of Included Files\n",
            "| File | Mode | Language | Tokens |\n",
            "| :--- | :--- | :--- | :--- |\n",
            "| `src/z.py` | **FULL** | python | 1,000 |\n",
            "| `src/a.ts` | **SKELETON** | typescript | 500 |\n\n---\n\n",
            "### File: `src/z.py` (FULL)\n```python\nvalue = 1\n\n```\n\n",
            "### File: `src/a.ts` (SKELETON)\n```typescript\nfunction f() { /* ... */ }\n```\n"
        )
    );
    assert_eq!(
        results
            .iter()
            .map(|r| r.content.clone())
            .collect::<Vec<_>>(),
        original
    );
}

#[test]
fn markdown_fences_are_longer_than_every_embedded_backtick_run() {
    for length in 0..32 {
        let content = format!(
            "中文 🐾\r\n{}\nexample\n{}\n",
            "`".repeat(length),
            "`".repeat(length / 2)
        );
        let result = file("文档.py", "python", "UNCHANGED", 20, 20, &content);
        let output = format_markdown(&[result], &RepoStats::default());
        let fence = "`".repeat(3.max(length + 1));
        let section = output
            .split_once("### File: `文档.py` (UNCHANGED)\n")
            .unwrap()
            .1;
        assert_eq!(
            section,
            format!("{fence}python\n{content}\n{fence}\n"),
            "run {length}"
        );
    }
}

#[test]
fn fences_are_chosen_independently_for_each_file() {
    let results = [
        file("a.py", "python", "FULL", 1, 1, "``````"),
        file("b.js", "javascript", "SKELETON", 1, 1, "const x = 1;"),
    ];
    let output = format_markdown(&results, &compute_stats(&results));
    assert!(output.contains("```````python\n``````\n```````"));
    assert!(output.contains("```javascript\nconst x = 1;\n```"));
}

#[test]
fn terminal_report_golden_includes_grouping_precision_version_and_delimiters() {
    let stats = RepoStats {
        file_count: 2,
        orig_tokens: 12_345,
        skel_tokens: 1_234,
        saved_tokens: 11_111,
        ratio: 90.004,
        savings_usd: 0.033333,
    };
    let expected = format!("\n{}\n [skel vtest-version] Codebase Context Compression Report\n{}\n Files processed:    2\n Original tokens:    12,345\n Skeleton tokens:    1,234\n Compression ratio:  90.0% reduction\n Est. cost saved:    $0.0333 (Claude 3.5 Sonnet tier)\n{}\n", "=".repeat(60), "-".repeat(60), "=".repeat(60));
    assert_eq!(format_terminal_report(&stats, "test-version"), expected);
    let empty = format_terminal_report(&RepoStats::default(), "0");
    assert!(empty.contains("0.0% reduction"));
    assert!(empty.contains("$0.0000"));
    assert!(!empty.contains("NaN") && !empty.contains("inf"));
}
